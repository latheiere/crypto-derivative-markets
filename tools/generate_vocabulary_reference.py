"""Generate the Antora vocabulary reference from public CDM definitions."""

from __future__ import annotations

import argparse
from enum import Enum
from pathlib import Path
from typing import Iterable, Type

import cdm
from cdm import (
    NATIVE_IDENTITY_NAMESPACE_PATTERN,
    AssetRelationship,
    ContractValueUnit,
    ConversionFormula,
    ConversionIssueCode,
    ConversionStatus,
    DataPointKind,
    DerivationKind,
    DescriptorAssessmentState,
    DescriptorIssueCode,
    FundingIntervalKind,
    FundingMechanism,
    FundingRateKind,
    InstrumentCapability,
    InstrumentKind,
    MarginAssetRelationship,
    MaturityFamily,
    MeasurementUnit,
    NativeIdentityNamespace,
    NativeIdentityRole,
    NativeIdentitySelectionStatus,
    NotionalDenomination,
    OpenInterestMeasure,
    PayoffFamily,
    SettlementMethod,
    TemporalMode,
    classify_maturity,
    classify_payoff,
    data_point_rules,
    schema_ids,
    standard_native_identity_namespaces,
)

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs/modules/ROOT/partials/generated-vocabulary.adoc"


def _enum_table(title: str, values: Type[Enum]) -> Iterable[str]:
    yield f".{title}"
    yield '[cols="1,2",options="header"]'
    yield "|==="
    yield "|Wire value |Python member"
    for item in values:
        yield f"|`{item.value}` |`{type(item).__name__}.{item.name}`"
    yield "|==="
    yield ""


def render() -> str:
    lines = [
        "// Generated by tools/generate_vocabulary_reference.py. Do not edit.",
        "",
    ]
    sections = (
        ("Instrument kinds", InstrumentKind),
        ("Contract-value units", ContractValueUnit),
        ("Settlement methods", SettlementMethod),
        ("Settlement-asset relationships", AssetRelationship),
        ("Margin-asset relationships", MarginAssetRelationship),
        ("Funding mechanisms", FundingMechanism),
        ("Payoff families", PayoffFamily),
        ("Maturity families", MaturityFamily),
        ("Instrument capabilities", InstrumentCapability),
        ("Descriptor assessment states", DescriptorAssessmentState),
        ("Descriptor issue codes", DescriptorIssueCode),
        ("Datapoint kinds", DataPointKind),
        ("Funding interval evidence", FundingIntervalKind),
        ("Funding rate kinds", FundingRateKind),
        ("Temporal modes", TemporalMode),
        ("Measurement units", MeasurementUnit),
        ("Notional denominations", NotionalDenomination),
        ("Derivation kinds", DerivationKind),
        ("Open-interest measures", OpenInterestMeasure),
        ("Conversion statuses", ConversionStatus),
        ("Conversion issue codes", ConversionIssueCode),
        ("Native identity roles", NativeIdentityRole),
        ("Native identity selection statuses", NativeIdentitySelectionStatus),
    )
    exported_enum_types: set[Type[Enum]] = set()
    for name in cdm.__all__:
        value = getattr(cdm, name)
        if isinstance(value, type) and issubclass(value, Enum):
            exported_enum_types.add(value)
    documented_enum_types: set[Type[Enum]] = {enum_type for _, enum_type in sections} | {
        ConversionFormula
    }
    if documented_enum_types != exported_enum_types:
        missing = sorted(
            enum_type.__name__ for enum_type in exported_enum_types - documented_enum_types
        )
        extra = sorted(
            enum_type.__name__ for enum_type in documented_enum_types - exported_enum_types
        )
        raise RuntimeError(f"public enum documentation mismatch; missing={missing}, extra={extra}")
    for title, enum_type in sections:
        lines.extend(_enum_table(title, enum_type))

    namespace_members = (
        ("REST", NativeIdentityNamespace.REST),
        ("REST_INSTRUMENT_CATALOG", NativeIdentityNamespace.REST_INSTRUMENT_CATALOG),
        ("REST_DERIVATIVE_STATUS", NativeIdentityNamespace.REST_DERIVATIVE_STATUS),
        ("WEBSOCKET", NativeIdentityNamespace.WEBSOCKET),
        ("FIX", NativeIdentityNamespace.FIX),
        ("RPC", NativeIdentityNamespace.RPC),
    )
    if tuple(value for _, value in namespace_members) != standard_native_identity_namespaces():
        raise RuntimeError("standard native identity namespace documentation mismatch")
    lines.extend(
        (
            ".Native identity namespaces",
            '[cols="2,3",options="header"]',
            "|===",
            "|Wire value |Python member",
        )
    )
    lines.extend(
        f"|`{namespace}` |`NativeIdentityNamespace.{name}`" for name, namespace in namespace_members
    )
    lines.extend(
        (
            "|===",
            "",
            ".Native identity namespace validation pattern",
            f"`{NATIVE_IDENTITY_NAMESPACE_PATTERN}`",
            "",
        )
    )

    lines.extend((".Schema identifiers", '[cols="1",options="header"]', "|===", "|URN"))
    lines.extend(f"|`{schema_id}`" for schema_id in schema_ids())
    lines.extend(("|===", ""))

    lines.extend(
        (
            ".Payoff classification",
            '[cols="1,1,1",options="header"]',
            "|===",
            "|Contract-value unit |Settlement relationship |Payoff family",
        )
    )
    for unit in ContractValueUnit:
        for relationship in AssetRelationship:
            family = classify_payoff(unit, relationship)
            lines.append(f"|`{unit.value}` |`{relationship.value}` |`{family.value}`")
    lines.extend(("|===", "", ".Maturity classification", '[cols="1,1",options="header"]'))
    lines.extend(("|===", "|Instrument kind |Maturity family"))
    for instrument_kind in InstrumentKind:
        lines.append(f"|`{instrument_kind.value}` |`{classify_maturity(instrument_kind).value}`")
    lines.extend(("|===", ""))

    lines.extend(
        (
            ".Datapoint constraints",
            '[cols="2,1,2,1",options="header"]',
            "|===",
            "|Kind |Unit |Temporal modes |Denomination",
        )
    )
    for data_point_kind, rule in sorted(data_point_rules().items(), key=lambda item: item[0].value):
        temporal_modes = ", ".join(
            f"`{mode.value}`" for mode in sorted(rule.temporal_modes, key=lambda mode: mode.value)
        )
        denomination = "required" if rule.requires_denomination else "prohibited"
        lines.append(
            f"|`{data_point_kind.value}` |`{rule.unit.value}` |{temporal_modes} |{denomination}"
        )
    lines.extend(
        (
            "|===",
            "",
            ".Exact open-interest formula identifiers",
            '[cols="2,3",options="header"]',
            "|===",
            "|Python member |Identifier",
        )
    )
    lines.extend(
        f"|`ConversionFormula.{formula.name}` |`{formula.value}`" for formula in ConversionFormula
    )
    lines.append("|===")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"generated reference is stale: {OUTPUT}")
        return 0
    OUTPUT.write_text(expected, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
